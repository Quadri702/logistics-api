/**
 * @swagger
 * /api/payments/initialize/{shipmentId}:
 *   post:
 *     summary: Initialize payment for a shipment
 *     description: Initializes a Paystack payment for the authenticated customer's shipment.
 *     tags:
 *       - Payments
 *     parameters:
 *       - in: path
 *         name: shipmentId
 *         required: true
 *         schema:
 *           type: string
 *         description: ID of the shipment to pay for
 *     responses:
 *       201:
 *         description: Payment initialized successfully
 *       400:
 *         description: Payment already exists for this shipment
 *       401:
 *         description: Authentication required
 *       403:
 *         description: User can only pay for their own shipment
 *       404:
 *         description: Shipment or customer not found
 */

/**
 * @swagger
 * /api/payments/verify/{reference}:
 *   get:
 *     summary: Verify a payment
 *     description: Verifies a payment with Paystack and updates the payment and shipment status when successful.
 *     tags:
 *       - Payments
 *     parameters:
 *       - in: path
 *         name: reference
 *         required: true
 *         schema:
 *           type: string
 *         description: Payment reference generated by the API
 *         example: LGX-PAY-7A3F9B2C1D4E5F67
 *     responses:
 *       200:
 *         description: Payment verification completed
 *       400:
 *         description: Unable to verify payment with Paystack
 *       401:
 *         description: Authentication required
 *       403:
 *         description: User can only verify their own payment
 *       404:
 *         description: Payment not found
 */

/**
 * @swagger
 * /api/payments/webhook:
 *   post:
 *     summary: Receive Paystack webhook events
 *     description: Receives and validates webhook events sent by Paystack using the x-paystack-signature header.
 *     tags:
 *       - Payments
 *     security: []
 *     parameters:
 *       - in: header
 *         name: x-paystack-signature
 *         required: true
 *         schema:
 *           type: string
 *         description: HMAC SHA-512 signature generated by Paystack
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             properties:
 *               event:
 *                 type: string
 *                 example: charge.success
 *               data:
 *                 type: object
 *                 properties:
 *                   id:
 *                     type: integer
 *                     example: 123456789
 *                   status:
 *                     type: string
 *                     example: success
 *                   reference:
 *                     type: string
 *                     example: LGX-PAY-7A3F9B2C1D4E5F67
 *                   amount:
 *                     type: integer
 *                     description: Payment amount in kobo
 *                     example: 500000
 *     responses:
 *       200:
 *         description: Webhook received successfully
 *       400:
 *         description: Missing signature, missing request body or payment amount mismatch
 *       401:
 *         description: Invalid Paystack signature
 *       404:
 *         description: Payment not found
 */
